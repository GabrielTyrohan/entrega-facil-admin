-- =====================================================================
-- Fase 4 — Pedidos do vendedor
--
-- O vendedor (app, online) pede cestas e/ou produtos avulsos. O pedido
-- fica pendente até uma funcionária (cestas_vendedor/produtos/expedição)
-- ou o dono aprovar — total ou parcialmente — ou recusar com motivo.
--
-- Aprovar reaproveita as funções que já existem:
--   cestas  → registrar_entrega_cestas   (estoque geral → estoque do vendedor)
--   avulsos → criar_entrega_avulsa_segura
-- Tudo numa transação: se faltar estoque, nada é gravado.
--
-- Os clientes (app/admin) só leem as tabelas; toda escrita é por função.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 0. Entregas avulsas: aceitar a permissão cestas_vendedor (Fase 3)
--    As três funções têm uma 2ª checagem que só aceitava produtos/expedição.
-- ---------------------------------------------------------------------
do $$
declare
  v_nome text;
  v_def text;
  v_novo text;
  v_antigo constant text := 'coalesce((f.permissoes->>''expedicao'')::boolean,false)=true';
  v_trocado constant text := 'coalesce((f.permissoes->>''expedicao'')::boolean,false)=true'
                             || ' or coalesce((f.permissoes->>''cestas_vendedor'')::boolean,false)=true';
begin
  foreach v_nome in array array['criar_entrega_avulsa_segura', 'atualizar_entrega_avulsa_segura', 'excluir_entrega_avulsa_segura']
  loop
    select pg_get_functiondef(p.oid) into v_def
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.proname = v_nome;

    if v_def is null then
      raise exception 'Função % não encontrada', v_nome;
    end if;

    if position('cestas_vendedor' in v_def) > 0 then
      continue; -- já ajustada
    end if;

    v_novo := replace(v_def, v_antigo, v_trocado);
    if v_novo = v_def then
      raise exception 'Trecho de permissão não encontrado em %', v_nome;
    end if;

    execute v_novo;
  end loop;
end;
$$;


-- ---------------------------------------------------------------------
-- 0b. registrar_entrega_cestas gravava usuario_tipo = 'administrador', valor
--     recusado pela CHECK de movimentacoes_estoque ('admin','funcionario',
--     'vendedor'). Resultado: o dono não conseguia liberar cestas
--     (última liberação registrada: 11/07/2026).
-- ---------------------------------------------------------------------
do $$
declare
  v_def text;
  v_novo text;
begin
  select pg_get_functiondef('public.registrar_entrega_cestas(uuid,uuid,uuid,integer,uuid,text,text)'::regprocedure)
    into v_def;

  v_novo := replace(v_def, 'v_usuario_tipo := ''administrador'';', 'v_usuario_tipo := ''admin'';');
  if v_novo <> v_def then
    execute v_novo;
  elsif position('v_usuario_tipo := ''admin'';' in v_def) = 0 then
    raise exception 'registrar_entrega_cestas: trecho de usuario_tipo não encontrado';
  end if;
end;
$$;


-- ---------------------------------------------------------------------
-- 1. Tabelas
-- ---------------------------------------------------------------------
create table if not exists public.pedidos_vendedor (
  id uuid primary key default gen_random_uuid(),
  numero integer generated by default as identity,
  administrador_id uuid not null references public.administradores(id) on delete cascade,
  vendedor_id uuid not null references public.vendedores(id) on delete cascade,
  status text not null default 'pendente'
    check (status in ('pendente', 'aprovado', 'parcial', 'recusado', 'cancelado')),
  observacao text,
  resposta text,
  atendido_por uuid,
  atendido_por_nome text,
  atendido_em timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.pedidos_vendedor_itens (
  id uuid primary key default gen_random_uuid(),
  pedido_id uuid not null references public.pedidos_vendedor(id) on delete cascade,
  tipo text not null check (tipo in ('cesta', 'avulso')),
  cesta_id uuid references public.produtos(id) on delete set null,
  produto_cadastrado_id uuid references public.produtos_cadastrado(id) on delete set null,
  descricao text not null,
  quantidade_solicitada numeric not null check (quantidade_solicitada > 0),
  quantidade_atendida numeric not null default 0 check (quantidade_atendida >= 0),
  created_at timestamptz not null default now()
);

create index if not exists idx_pedidos_vendedor_admin_status
  on public.pedidos_vendedor (administrador_id, status, created_at desc);
create index if not exists idx_pedidos_vendedor_vendedor
  on public.pedidos_vendedor (vendedor_id, created_at desc);
create index if not exists idx_pedidos_vendedor_itens_pedido
  on public.pedidos_vendedor_itens (pedido_id);

alter table public.pedidos_vendedor enable row level security;
alter table public.pedidos_vendedor_itens enable row level security;

drop policy if exists pedidos_vendedor_leitura on public.pedidos_vendedor;
create policy pedidos_vendedor_leitura on public.pedidos_vendedor
  for select to authenticated
  using (public.is_super_admin() or public.can_operate_cestas(administrador_id));

drop policy if exists pedidos_vendedor_itens_leitura on public.pedidos_vendedor_itens;
create policy pedidos_vendedor_itens_leitura on public.pedidos_vendedor_itens
  for select to authenticated
  using (exists (
    select 1 from public.pedidos_vendedor p
    where p.id = pedidos_vendedor_itens.pedido_id
      and (public.is_super_admin() or public.can_operate_cestas(p.administrador_id))
  ));

-- Aviso em tempo real de pedido novo no admin
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'pedidos_vendedor'
  ) then
    alter publication supabase_realtime add table public.pedidos_vendedor;
  end if;
end;
$$;


-- ---------------------------------------------------------------------
-- 2. Funções usadas pelo app (via Edge Function, service_role)
-- ---------------------------------------------------------------------
create or replace function public.criar_pedido_vendedor(
  p_vendedor_id uuid,
  p_itens jsonb,
  p_observacao text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_admin_id uuid;
  v_pedido_id uuid;
  v_numero integer;
  v_item jsonb;
  v_tipo text;
  v_id uuid;
  v_qtd numeric;
  v_nome text;
  v_pendentes integer;
begin
  if coalesce(auth.role(), '') <> 'service_role' then
    raise exception 'Uso exclusivo do servidor' using errcode = '42501';
  end if;

  select v.administrador_id into v_admin_id
  from public.vendedores v
  where v.id = p_vendedor_id and v.ativo = true;
  if v_admin_id is null then
    raise exception 'Vendedor não encontrado ou inativo' using errcode = 'P0002';
  end if;
  if exists (select 1 from public.vendedores where id = p_vendedor_id and coalesce(bloqueado, false)) then
    raise exception 'Seu acesso está bloqueado. Regularize a assinatura para fazer pedidos.' using errcode = '42501';
  end if;

  if p_itens is null or jsonb_typeof(p_itens) <> 'array' or jsonb_array_length(p_itens) = 0 then
    raise exception 'O pedido precisa ter pelo menos 1 item' using errcode = '22023';
  end if;
  if jsonb_array_length(p_itens) > 50 then
    raise exception 'O pedido pode ter no máximo 50 itens' using errcode = '22023';
  end if;

  select count(*) into v_pendentes
  from public.pedidos_vendedor
  where vendedor_id = p_vendedor_id and status = 'pendente';
  if v_pendentes >= 5 then
    raise exception 'Você já tem % pedidos aguardando. Aguarde o atendimento antes de enviar outro.', v_pendentes
      using errcode = '22023';
  end if;

  insert into public.pedidos_vendedor (administrador_id, vendedor_id, observacao)
  values (v_admin_id, p_vendedor_id, nullif(btrim(left(coalesce(p_observacao, ''), 500)), ''))
  returning id, numero into v_pedido_id, v_numero;

  for v_item in select value from jsonb_array_elements(p_itens)
  loop
    begin
      v_tipo := v_item->>'tipo';
      v_id := (v_item->>'id')::uuid;
      v_qtd := (v_item->>'quantidade')::numeric;
    exception when others then
      raise exception 'Item inválido no pedido' using errcode = '22023';
    end;

    if v_qtd is null or v_qtd <= 0 or v_qtd > 1000 then
      raise exception 'Quantidade inválida no pedido' using errcode = '22023';
    end if;

    if v_tipo = 'cesta' then
      if v_qtd <> trunc(v_qtd) then
        raise exception 'Quantidade de cestas precisa ser um número inteiro' using errcode = '22023';
      end if;
      select p.nome into v_nome
      from public.produtos p
      where p.id = v_id and p.vendedor_id = p_vendedor_id and coalesce(p.ativo, true) = true;
      if v_nome is null then
        raise exception 'Cesta não encontrada para este vendedor' using errcode = 'P0002';
      end if;

      insert into public.pedidos_vendedor_itens (pedido_id, tipo, cesta_id, descricao, quantidade_solicitada)
      values (v_pedido_id, 'cesta', v_id, v_nome, v_qtd);

    elsif v_tipo = 'avulso' then
      select pc.produto_nome into v_nome
      from public.produtos_cadastrado pc
      where pc.id = v_id and pc.administrador_id = v_admin_id and coalesce(pc.ativo, true) = true;
      if v_nome is null then
        raise exception 'Produto não encontrado nesta empresa' using errcode = 'P0002';
      end if;

      insert into public.pedidos_vendedor_itens (pedido_id, tipo, produto_cadastrado_id, descricao, quantidade_solicitada)
      values (v_pedido_id, 'avulso', v_id, v_nome, v_qtd);

    else
      raise exception 'Tipo de item inválido: use cesta ou avulso' using errcode = '22023';
    end if;

    v_nome := null;
  end loop;

  return jsonb_build_object('id', v_pedido_id, 'numero', v_numero, 'status', 'pendente');
end;
$$;

revoke all on function public.criar_pedido_vendedor(uuid, jsonb, text) from public, anon, authenticated;
grant execute on function public.criar_pedido_vendedor(uuid, jsonb, text) to service_role;


create or replace function public.listar_pedidos_vendedor(p_vendedor_id uuid, p_limite integer default 20)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if coalesce(auth.role(), '') <> 'service_role' then
    raise exception 'Uso exclusivo do servidor' using errcode = '42501';
  end if;

  return coalesce((
    select jsonb_agg(x.pedido order by x.created_at desc)
    from (
      select p.created_at,
        jsonb_build_object(
          'id', p.id,
          'numero', p.numero,
          'status', p.status,
          'observacao', p.observacao,
          'resposta', p.resposta,
          'atendido_por_nome', p.atendido_por_nome,
          'atendido_em', p.atendido_em,
          'created_at', p.created_at,
          'itens', coalesce((
            select jsonb_agg(jsonb_build_object(
              'id', i.id,
              'tipo', i.tipo,
              'descricao', i.descricao,
              'quantidade_solicitada', i.quantidade_solicitada,
              'quantidade_atendida', i.quantidade_atendida
            ) order by i.created_at)
            from public.pedidos_vendedor_itens i
            where i.pedido_id = p.id
          ), '[]'::jsonb)
        ) as pedido
      from public.pedidos_vendedor p
      where p.vendedor_id = p_vendedor_id
      order by p.created_at desc
      limit greatest(1, least(coalesce(p_limite, 20), 50))
    ) x
  ), '[]'::jsonb);
end;
$$;

revoke all on function public.listar_pedidos_vendedor(uuid, integer) from public, anon, authenticated;
grant execute on function public.listar_pedidos_vendedor(uuid, integer) to service_role;


create or replace function public.cancelar_pedido_vendedor(p_vendedor_id uuid, p_pedido_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
begin
  if coalesce(auth.role(), '') <> 'service_role' then
    raise exception 'Uso exclusivo do servidor' using errcode = '42501';
  end if;

  update public.pedidos_vendedor
  set status = 'cancelado', updated_at = now()
  where id = p_pedido_id and vendedor_id = p_vendedor_id and status = 'pendente';

  if not found then
    raise exception 'Só é possível cancelar pedido seu que ainda está aguardando' using errcode = '22023';
  end if;

  return jsonb_build_object('id', p_pedido_id, 'status', 'cancelado');
end;
$$;

revoke all on function public.cancelar_pedido_vendedor(uuid, uuid) from public, anon, authenticated;
grant execute on function public.cancelar_pedido_vendedor(uuid, uuid) to service_role;


-- ---------------------------------------------------------------------
-- 3. Funções usadas pelo admin (funcionária/dono)
-- ---------------------------------------------------------------------
create or replace function public.atender_pedido_vendedor(
  p_pedido_id uuid,
  p_itens jsonb,
  p_resposta text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_pedido public.pedidos_vendedor%rowtype;
  v_item record;
  v_qtd numeric;
  v_avulsos jsonb := '[]'::jsonb;
  v_total_solicitado numeric := 0;
  v_total_atendido numeric := 0;
  v_status text;
  v_nome text;
  v_obs text;
begin
  if auth.uid() is null then
    raise exception 'Usuário não autenticado' using errcode = '42501';
  end if;

  select * into v_pedido from public.pedidos_vendedor where id = p_pedido_id for update;
  if not found then
    raise exception 'Pedido não encontrado' using errcode = 'P0002';
  end if;
  if not public.can_operate_cestas(v_pedido.administrador_id) then
    raise exception 'Sem permissão para atender pedidos desta empresa' using errcode = '42501';
  end if;
  if v_pedido.status <> 'pendente' then
    raise exception 'Este pedido já foi %', v_pedido.status using errcode = '22023';
  end if;
  if p_itens is null or jsonb_typeof(p_itens) <> 'array' then
    raise exception 'Informe as quantidades atendidas' using errcode = '22023';
  end if;
  if exists (
    select 1 from public.vendedores v
    where v.id = v_pedido.vendedor_id and (not coalesce(v.ativo, true) or coalesce(v.bloqueado, false))
  ) then
    raise exception 'O vendedor está inativo ou bloqueado (assinatura vencida). Recuse o pedido ou regularize antes.'
      using errcode = '22023';
  end if;

  v_obs := format('Pedido #%s do vendedor', v_pedido.numero);

  for v_item in
    select i.*, coalesce((
      select (x->>'quantidade')::numeric
      from jsonb_array_elements(p_itens) x
      where (x->>'item_id')::uuid = i.id
      limit 1
    ), 0) as qtd_informada
    from public.pedidos_vendedor_itens i
    where i.pedido_id = p_pedido_id
    order by i.created_at
  loop
    v_qtd := v_item.qtd_informada;
    if v_qtd < 0 or v_qtd > v_item.quantidade_solicitada then
      raise exception 'Quantidade atendida de "%" deve ficar entre 0 e %', v_item.descricao, v_item.quantidade_solicitada
        using errcode = '22023';
    end if;

    v_total_solicitado := v_total_solicitado + v_item.quantidade_solicitada;
    v_total_atendido := v_total_atendido + v_qtd;

    if v_qtd > 0 then
      if v_item.tipo = 'cesta' then
        if v_qtd <> trunc(v_qtd) then
          raise exception 'Quantidade de cestas precisa ser um número inteiro' using errcode = '22023';
        end if;
        if v_item.cesta_id is null then
          raise exception 'A cesta "%" não existe mais', v_item.descricao using errcode = 'P0002';
        end if;
        -- Estoque geral → estoque do vendedor (falha se faltar estoque)
        perform public.registrar_entrega_cestas(
          null, v_pedido.vendedor_id, v_item.cesta_id, v_qtd::integer, null, null, v_obs
        );
      else
        if v_item.produto_cadastrado_id is null then
          raise exception 'O produto "%" não existe mais', v_item.descricao using errcode = 'P0002';
        end if;
        v_avulsos := v_avulsos || jsonb_build_array(jsonb_build_object(
          'produtoId', v_item.produto_cadastrado_id, 'quantidade', v_qtd));
      end if;
    end if;

    update public.pedidos_vendedor_itens set quantidade_atendida = v_qtd where id = v_item.id;
  end loop;

  if v_total_atendido = 0 then
    raise exception 'Nenhuma quantidade informada. Para não atender, use Recusar.' using errcode = '22023';
  end if;

  if jsonb_array_length(v_avulsos) > 0 then
    perform public.criar_entrega_avulsa_segura(v_pedido.vendedor_id, v_avulsos, v_obs);
  end if;

  v_status := case when v_total_atendido >= v_total_solicitado then 'aprovado' else 'parcial' end;

  select a.nome into v_nome from public.administradores a where a.id = auth.uid();
  if v_nome is null then
    select f.nome into v_nome from public.funcionarios f where f.auth_user_id = auth.uid() limit 1;
  end if;
  if v_nome is null then
    select d.nome into v_nome from public.desenvolvedores d where d.user_id = auth.uid() limit 1;
  end if;

  update public.pedidos_vendedor
  set status = v_status,
      resposta = nullif(btrim(coalesce(p_resposta, '')), ''),
      atendido_por = auth.uid(),
      atendido_por_nome = v_nome,
      atendido_em = now(),
      updated_at = now()
  where id = p_pedido_id;

  return jsonb_build_object('id', p_pedido_id, 'status', v_status);
end;
$$;

revoke all on function public.atender_pedido_vendedor(uuid, jsonb, text) from public, anon;
grant execute on function public.atender_pedido_vendedor(uuid, jsonb, text) to authenticated, service_role;


create or replace function public.recusar_pedido_vendedor(p_pedido_id uuid, p_motivo text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_pedido public.pedidos_vendedor%rowtype;
  v_nome text;
begin
  if auth.uid() is null then
    raise exception 'Usuário não autenticado' using errcode = '42501';
  end if;
  if nullif(btrim(coalesce(p_motivo, '')), '') is null then
    raise exception 'Informe o motivo da recusa' using errcode = '22023';
  end if;

  select * into v_pedido from public.pedidos_vendedor where id = p_pedido_id for update;
  if not found then
    raise exception 'Pedido não encontrado' using errcode = 'P0002';
  end if;
  if not public.can_operate_cestas(v_pedido.administrador_id) then
    raise exception 'Sem permissão para atender pedidos desta empresa' using errcode = '42501';
  end if;
  if v_pedido.status <> 'pendente' then
    raise exception 'Este pedido já foi %', v_pedido.status using errcode = '22023';
  end if;

  select a.nome into v_nome from public.administradores a where a.id = auth.uid();
  if v_nome is null then
    select f.nome into v_nome from public.funcionarios f where f.auth_user_id = auth.uid() limit 1;
  end if;
  if v_nome is null then
    select d.nome into v_nome from public.desenvolvedores d where d.user_id = auth.uid() limit 1;
  end if;

  update public.pedidos_vendedor
  set status = 'recusado',
      resposta = btrim(left(p_motivo, 500)),
      atendido_por = auth.uid(),
      atendido_por_nome = v_nome,
      atendido_em = now(),
      updated_at = now()
  where id = p_pedido_id;

  return jsonb_build_object('id', p_pedido_id, 'status', 'recusado');
end;
$$;

revoke all on function public.recusar_pedido_vendedor(uuid, text) from public, anon;
grant execute on function public.recusar_pedido_vendedor(uuid, text) to authenticated, service_role;
